export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

// Measure the pixel width of `text` rendered at `scale` with a 1px (scaled)
// gap between glyphs.
export function measureText(text, scale = 2) {
  if (text.length === 0) return 0;
  const glyph = GLYPH_WIDTH * scale;
  const gap = scale;
  return text.length * glyph + (text.length - 1) * gap;
}

// Return the glyph matrix for a character, falling back to a blank cell.
export function glyphFor(ch) {
  const upper = GLYPHS[ch] ? ch : ch.toUpperCase();
  return GLYPHS[upper] || GLYPHS[' '];
}
